namespace SmartVectorDotNet.Generators;


[Generator(LanguageNames.CSharp)]
public sealed partial class VectorizationCalculatorGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        context.RegisterPostInitializationOutput(EmitConstants);

        var source = context.SyntaxProvider.CreateSyntaxProvider(
            InterceptorPredicate,
            InterceptorTransform)
            .Where(static x => x is not null);

        context.RegisterSourceOutput(
            source,
            EmitSource!);
    }


    private static bool InterceptorPredicate(SyntaxNode node, CancellationToken token) =>
        node is InvocationExpressionSyntax {
            Expression: MemberAccessExpressionSyntax {
                Name.Identifier.Text: "Calculate"
            }
        };


    private static InterceptorInfo? InterceptorTransform(GeneratorSyntaxContext context, CancellationToken token)
    {
        if (context.Node is not InvocationExpressionSyntax invocation)
        {
            return null;
        }
        if (context.SemanticModel.GetSymbolInfo(invocation).Symbol is not IMethodSymbol methodSymbol)
        {
            return null;
        }
        if (!methodSymbol.IsGenericMethod)
        {
            return null;
        }
        var methodIdentifier = methodSymbol.OriginalDefinition.ToDisplayString();
        if (!methodIdentifier.StartsWith("SmartVectorDotNet.Vectorization.Calculate<T>"))
        {
            return null;
        }
        if(context.SemanticModel.GetInterceptableLocation(invocation) is not { } location)
        {
            return null;
        }
        return new(location, [.. invocation.ArgumentList.Arguments]);
    }


    private static void EmitConstants(IncrementalGeneratorPostInitializationContext context)
    {
        context.AddSource(
            "SmartVectorDotNet.VectorizationExtensions.Calculate.g.cs",
            """
            // <auto-generated>
            // This file is auto-generated by SmartVectorDotNet.Generators.VectorizationCalculatorGenerator
            // Do not edit this file manually.
